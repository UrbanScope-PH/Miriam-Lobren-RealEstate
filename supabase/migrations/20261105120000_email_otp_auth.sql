-- ==============================================================================
-- UrbanScope: email verification and password recovery OTPs
-- ==============================================================================
-- New client accounts are created only after a server verifies a one-time email
-- code. Existing accounts are treated as verified to preserve current access.

ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ;

UPDATE public.users
SET email_verified_at = COALESCE(created_at, timezone('utc'::text, now()))
WHERE email_verified_at IS NULL;

CREATE OR REPLACE FUNCTION public.protect_user_email_verification()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
BEGIN
    IF session_user NOT IN ('postgres', 'supabase_admin') AND COALESCE(auth.role(), '') <> 'service_role' THEN
        IF TG_OP = 'INSERT' THEN
            NEW.role := 'client';
            NEW.email_verified_at := NULL;
        ELSIF NEW.role IS DISTINCT FROM OLD.role THEN
            RAISE EXCEPTION 'Role changes must use a verified server-side account-management flow.';
        ELSIF NEW.password_hash IS DISTINCT FROM OLD.password_hash THEN
            RAISE EXCEPTION 'Password changes must use a verified server-side authentication flow.';
        ELSIF NEW.email_verified_at IS DISTINCT FROM OLD.email_verified_at THEN
            RAISE EXCEPTION 'Email verification must use a verified server-side authentication flow.';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_protect_user_email_verification ON public.users;
CREATE TRIGGER trg_protect_user_email_verification
    BEFORE INSERT OR UPDATE OF email_verified_at, password_hash, role ON public.users
    FOR EACH ROW EXECUTE FUNCTION public.protect_user_email_verification();

CREATE TABLE IF NOT EXISTS public.auth_email_challenges (
    email TEXT NOT NULL,
    purpose TEXT NOT NULL CHECK (purpose IN ('register', 'password_reset')),
    code_hash TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    PRIMARY KEY (email, purpose)
);

CREATE TABLE IF NOT EXISTS public.auth_email_challenge_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_auth_email_challenge_requests_ip_time
    ON public.auth_email_challenge_requests (ip_hash, created_at);

ALTER TABLE public.auth_email_challenges ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auth_email_challenge_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.auth_email_challenges FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.auth_email_challenge_requests FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.auth_email_challenges TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.auth_email_challenge_requests TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.auth_email_challenge_requests_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.issue_auth_email_challenge(
    p_email TEXT,
    p_purpose TEXT,
    p_code_hash TEXT,
    p_ip_hash TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    current_time_utc TIMESTAMPTZ := timezone('utc'::text, now());
    recent_ip_requests BIGINT;
BEGIN
    IF p_purpose NOT IN ('register', 'password_reset') OR
       length(p_email) > 254 OR length(p_code_hash) <> 64 OR length(p_ip_hash) <> 64 THEN
        RETURN FALSE;
    END IF;

    PERFORM pg_advisory_xact_lock(hashtextextended(p_email || ':' || p_purpose, 0));

    DELETE FROM public.auth_email_challenge_requests
    WHERE created_at < current_time_utc - INTERVAL '24 hours';

    IF EXISTS (
        SELECT 1 FROM public.auth_email_challenges
        WHERE email = p_email AND purpose = p_purpose
          AND created_at > current_time_utc - INTERVAL '60 seconds'
    ) THEN
        RETURN FALSE;
    END IF;

    SELECT COUNT(*) INTO recent_ip_requests
    FROM public.auth_email_challenge_requests
    WHERE ip_hash = p_ip_hash AND created_at > current_time_utc - INTERVAL '1 hour';

    IF recent_ip_requests >= 10 THEN
        RETURN FALSE;
    END IF;

    INSERT INTO public.auth_email_challenge_requests (ip_hash, created_at)
    VALUES (p_ip_hash, current_time_utc);

    INSERT INTO public.auth_email_challenges (email, purpose, code_hash, expires_at, attempts, created_at)
    VALUES (p_email, p_purpose, p_code_hash, current_time_utc + INTERVAL '10 minutes', 0, current_time_utc)
    ON CONFLICT (email, purpose) DO UPDATE SET
        code_hash = EXCLUDED.code_hash,
        expires_at = EXCLUDED.expires_at,
        attempts = 0,
        created_at = EXCLUDED.created_at;

    RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.consume_auth_email_challenge(
    p_email TEXT,
    p_purpose TEXT,
    p_code_hash TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    challenge public.auth_email_challenges%ROWTYPE;
BEGIN
    SELECT * INTO challenge
    FROM public.auth_email_challenges
    WHERE email = p_email AND purpose = p_purpose
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN FALSE;
    END IF;

    IF challenge.expires_at <= timezone('utc'::text, now()) OR challenge.attempts >= 5 THEN
        DELETE FROM public.auth_email_challenges WHERE email = p_email AND purpose = p_purpose;
        RETURN FALSE;
    END IF;

    IF challenge.code_hash = p_code_hash THEN
        DELETE FROM public.auth_email_challenges WHERE email = p_email AND purpose = p_purpose;
        RETURN TRUE;
    END IF;

    UPDATE public.auth_email_challenges
    SET attempts = attempts + 1
    WHERE email = p_email AND purpose = p_purpose;
    RETURN FALSE;
END;
$$;

REVOKE ALL ON FUNCTION public.issue_auth_email_challenge(TEXT, TEXT, TEXT, TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.consume_auth_email_challenge(TEXT, TEXT, TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.issue_auth_email_challenge(TEXT, TEXT, TEXT, TEXT) TO service_role;
GRANT EXECUTE ON FUNCTION public.consume_auth_email_challenge(TEXT, TEXT, TEXT) TO service_role;
